// Move the previous Vite build output out of the embed tree before a new one
// lands — never delete it.
//
// vite.config.ts keeps emptyOutDir:false so the embed directory never loses its
// .gitkeep, which means every build only ever ADDS files: each content-hashed
// asset from the previous run stays behind forever. Six runs of that left 506
// files / 31.8 MB in internal/server/webdist, of which only the last run's ~99
// chunks are referenced by index.html — and `//go:embed all:webdist` puts every
// one of them into both octo.exe and octo-desktop.exe.
//
// House rule: build products are never deleted outright. Everything this script
// clears is renamed into <repo>/.trash/<YYYYMMDD-HHMMSS>/ with a manifest.txt
// recording each file's original location and size, so a bad build can be
// recovered by hand. Only the three most recent recoveries are kept; older ones
// are moved again, into .trash/_expired/, and still never deleted.
//
// Idempotent: a missing entry is not an error. .gitkeep is never touched.

import { mkdir, readdir, rename, stat, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const webDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repoDir = resolve(webDir, '..')
const webdist = join(repoDir, 'internal', 'server', 'webdist')
const trashBase = join(repoDir, '.trash')
const expiredBase = join(trashBase, '_expired')

// Generated by the build; .gitkeep and anything else stays untouched.
const GENERATED = ['assets', 'dsh-startup', 'index.html', 'favicon.svg']

const KEEP_RECENT = 3

function stamp() {
  const d = new Date()
  const p = (n, w = 2) => String(n).padStart(w, '0')
  return (
    `${d.getFullYear()}${p(d.getMonth() + 1)}${p(d.getDate())}` +
    `-${p(d.getHours())}${p(d.getMinutes())}${p(d.getSeconds())}`
  )
}

// A unique destination: two builds inside the same second must not collide.
async function uniqueDir(base, name) {
  let candidate = join(base, name)
  let n = 1
  for (;;) {
    try {
      await stat(candidate)
      candidate = join(base, `${name}-${n++}`)
    } catch {
      return candidate
    }
  }
}

// Walk a moved tree and collect { rel, bytes } for every file.
async function walk(dir, prefix, out) {
  const entries = await readdir(dir, { withFileTypes: true })
  for (const e of entries) {
    const abs = join(dir, e.name)
    const rel = prefix ? `${prefix}/${e.name}` : e.name
    if (e.isDirectory()) {
      await walk(abs, rel, out)
    } else if (e.isFile()) {
      const fi = await stat(abs)
      out.push({ rel, bytes: fi.size })
    }
  }
}

// Keep the newest KEEP_RECENT recovery directories; move the rest into
// .trash/_expired/. Nothing is ever deleted.
async function expireOld() {
  let entries
  try {
    entries = await readdir(trashBase, { withFileTypes: true })
  } catch {
    return
  }
  const runs = entries
    .filter((e) => e.isDirectory() && /^\d{8}-\d{6}(-\d+)?$/.test(e.name))
    .map((e) => e.name)
    .sort()
  const stale = runs.slice(0, Math.max(0, runs.length - KEEP_RECENT))
  if (stale.length === 0) return
  await mkdir(expiredBase, { recursive: true })
  for (const name of stale) {
    const dest = await uniqueDir(expiredBase, name)
    await rename(join(trashBase, name), dest)
  }
}

// Which of the generated entries are actually present this run?
const present = []
for (const name of GENERATED) {
  const src = join(webdist, name)
  try {
    const fi = await stat(src)
    present.push({ name, src, isDir: fi.isDirectory(), bytes: fi.size })
  } catch {
    // not built yet — nothing to move
  }
}

if (present.length === 0) {
  // Nothing to clear: leave .trash alone rather than littering it with an
  // empty run. The single stdout line keeps CI logs uniform.
  console.log(`moved 0 files to ${trashBase}`)
} else {
  const destRoot = await uniqueDir(trashBase, stamp())
  await mkdir(destRoot, { recursive: true })

  const files = []
  for (const item of present) {
    const dest = join(destRoot, item.name)
    await rename(item.src, dest)
    if (item.isDir) {
      await walk(dest, item.name, files)
    } else {
      files.push({ rel: item.name, bytes: item.bytes })
    }
  }
  files.sort((a, b) => a.rel.localeCompare(b.rel))

  const lines = files.map(
    (f) => `${f.rel}\t${f.bytes}\t${join(webdist, f.rel)}`,
  )
  const header = [
    `# moved by web/scripts/clean-webdist.mjs at ${new Date().toISOString()}`,
    '# columns: relative-path <TAB> bytes <TAB> original-path',
    '',
  ]
  await writeFile(
    join(destRoot, 'manifest.txt'),
    `${header.join('\n')}${lines.join('\n')}\n`,
    'utf8',
  )

  await expireOld()
  console.log(`moved ${files.length} files to ${destRoot}`)
}
